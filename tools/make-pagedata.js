/**
 * Generates apps-script/PagesData.gs — the four pages as data, for installing
 * them into the app's Drive folder from inside the project.
 *
 *   node tools/make-pagedata.js
 *
 * WHY THIS EXISTS. Getting a new page into Drive needs either a file upload,
 * which cannot be driven or verified, or a fetch, which needs the external
 * request OAuth scope and makes the live pages depend on a server outside the
 * company. Carrying the bytes in the project needs neither: DriveApp is a
 * permission this project has had since the day it was built.
 *
 * Each page is stored as its lines, JSON-escaped, joined back with \n. Split
 * and join are exact inverses, so a file ending in a newline still does — and
 * the fingerprint check in Pages.gs is what proves it rather than this comment.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const PAGES = ['index.html', 'intake.html', 'approve.html', 'dashboard.html'];
const dir = path.join(__dirname, '..');

const out = [
  '/**',
  ' * Golden Choice — the four pages, as data.',
  ' *',
  ' * GENERATED by tools/make-pagedata.js. Do not edit by hand: it is written',
  ' * from pages/*.html and every byte is checked against PAGE_FINGERPRINTS in',
  ' * Web.gs before installPages() will write any of it to Drive.',
  ' *',
  ' * It is here rather than fetched so that installing a page needs nothing but',
  ' * the Drive permission this project already had, and so the live site never',
  ' * depends on a server outside the company.',
  ' */',
  ''
];

for (const name of PAGES) {
  const buf = fs.readFileSync(path.join(dir, 'pages', name));
  const text = buf.toString('utf8');
  const md5 = crypto.createHash('md5').update(buf).digest('hex');
  const lines = text.split('\n');
  out.push('/* ' + name + '  ' + buf.length + ' bytes  md5 ' + md5 + ' */');
  out.push('var PAGE_' + name.replace(/\W/g, '_').toUpperCase() + ' = [');
  out.push(lines.map(l => '  ' + JSON.stringify(l)).join(',\n'));
  out.push('].join(\'\\n\');');
  out.push('');
}

out.push('var PAGE_DATA = {');
out.push(PAGES.map(n => '  ' + JSON.stringify(n) + ': PAGE_' +
                        n.replace(/\W/g, '_').toUpperCase()).join(',\n'));
out.push('};');
out.push('');

const file = path.join(dir, 'apps-script', 'PagesData.gs');
fs.writeFileSync(file, out.join('\n'));

/* Prove the round trip here, before it is ever pasted anywhere. */
const vm = require('vm');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(file, 'utf8'), ctx);
let ok = 0;
for (const name of PAGES) {
  const want = fs.readFileSync(path.join(dir, 'pages', name));
  const got = Buffer.from(ctx.PAGE_DATA[name], 'utf8');
  const same = got.equals(want);
  console.log((same ? '  ok   ' : '  WRONG') + '  ' + name.padEnd(16) +
    got.length + ' bytes  ' + crypto.createHash('md5').update(got).digest('hex'));
  if (same) ok++;
}
console.log('\n' + fs.statSync(file).size + ' bytes written to apps-script/PagesData.gs');
console.log(ok + ' of ' + PAGES.length + ' pages round-trip byte-for-byte');
process.exit(ok === PAGES.length ? 0 : 1);
